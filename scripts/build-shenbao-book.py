def book_doc(figs: list[dict], body: str) -> str:
    out = [body, PB, "# 证明材料册\n",
           "\n> 本册按《2026 年行业可信数据空间创新发展试点项目申报书模板》「七、试点相关证明材料（一）—（四）」组织，"
           "附图编号与申报书正文引用一致。**全部实测基于合成数据，效应量与信号均为人为注入，不作为任何人群的流行病学结论。**\n",
           "\n## 证明一　申报单位基本材料\n",
           "\n【待装订】1. 申报单位法人证书；2. 近 3 年财务状况证明材料（事业单位口径）。\n"]
    for sec in ("二", "三", "四"):
        out.append(f"\n## {SEC_TITLE[sec]}\n\n{SEC_REQ[sec]}\n\n")
        for f in [x for x in figs if x["sec"] == sec]:
            out.append(f"**附图 {f['id']}**\n\n![]({resolve(f['file'])}){{width=15cm}}\n\n{f['caption']}\n")
            if f.get("extra"):
                out.append(f"\n{f['extra']}\n")
            out.append("\n")
        if sec == "四":
            out.append("\n【待装订文本件】1. 运营团队组建与岗位设置材料；2. 数据提供方、使用方、服务方合作协议或合作意向书；"
                       "3. 已编制或发布的规则机制文本（准入认证、流通使用、数据授权管理、收益分配、争议解决）；"
                       "4. 委托建设运营／技术合作协议；5. 数据分类分级清单与伦理审查或数据授权文件。\n")

    def safe_log(name: str) -> str:
        return (name.replace("huashan", "siteA").replace("ruijin", "siteB")
                    .replace("cdc-demo", "siteC").replace("cdc", "siteC"))

    logs = [(f["id"], safe_log(l)) for f in figs for l in f.get("logs", [])]
    out.append(PB + "# 附录\n\n## 一、日志 ↔ 附图 对应表（便于核验）\n\n| 附图 | 对应日志文件 |\n|---|---|\n")
    seen = set()
    for fid, log in logs:
        if (fid, log) in seen:
            continue
        seen.add((fid, log))
        out.append(f"| {fid} | `{log}` |\n")
    out.append("\n" + NOT_INCLUDED + "\n" + BOUNDARY)
    return "".join(out)


def main() -> int:
    figs = json.loads(FIG.read_text(encoding="utf-8"))
    body = BODY.read_text(encoding="utf-8")
    body = re.sub(r"> \*\*数据说明\*\*：[^\n]*\n", "", body)
    PLAN.write_text(plan_doc(figs), encoding="utf-8")
    book = book_doc(figs, body)
    # 合订本内的图片路径：figures.json 用相对 screenshots/ 的路径，合订本以 screenshots-x/ 占位后统一改写
    BOOK.write_text(book, encoding="utf-8")
    print(f"✓ {PLAN.relative_to(ROOT)}")
    print(f"✓ {BOOK.relative_to(ROOT)}（{len(figs)} 个附图号）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
