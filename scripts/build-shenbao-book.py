def resolve(fig_file: str) -> str:
    """图片解析顺序：打码副本 → 已脱敏渲染图 → 原图。"""
    name = pathlib.Path(fig_file).name
    for sub in ("screenshots-deck", "screenshots-redacted", "screenshots"):
        if (EV / sub / name).exists():
            return f"证明材料/{sub}/{name}"
    return f"证明材料/screenshots/{name}"


def md_link(f: dict) -> str:
    return f"`{f['file']}`"


