# 创建 Excel 工作簿
wb = Workbook()
ws = wb.active
ws.title = "字段清单"

# 添加表头
ws['A1'] = "序号"
ws['B1'] = "模块"
ws['C1'] = "字段名称"

# 解析数据并写入
row_num = 2  # 从第2行开始写入数据
for line in data_lines:
    # 跳过空行
    if not line.strip():
        continue
    
    # 按制表符分割
    parts = line.split('\t')
    
    # 根据不同行数处理
    if len(parts) >= 3:
        # 第1列：序号（可能有值也可能为空）
        seq = parts[0].strip() if parts[0].strip() else ''
        # 第2列：模块
        module = parts[1].strip() if parts[1].strip() else ''
        # 第3列：字段名称
        field = parts[2].strip() if parts[2].strip() else ''
        
        # 跳过标题行和无效行
        if seq == 'A' and module == 'B' and field == 'C':
            continue
        if seq == '1' and not module and not field:
            continue
        
        ws.cell(row=row_num, column=1, value=seq)
        ws.cell(row=row_num, column=2, value=module)
        ws.cell(row=row_num, column=3, value=field)
        row_num += 1
    elif len(parts) == 2:
        # 某些行可能只有两列
        seq = parts[0].strip() if parts[0].strip() else ''
        module = parts[1].strip() if parts[1].strip() else ''
        ws.cell(row=row_num, column=1, value=seq)
        ws.cell(row=row_num, column=2, value=module)
        row_num += 1

# 调整列宽
ws.column_dimensions['A'].width = 10
ws.column_dimensions['B'].width = 25
ws.column_dimensions['C'].width = 60

# 保存文件
wb.save('字段清单.xlsx')
print(f"Excel 文件已生成，共写入 {row_num - 2} 行数据。")